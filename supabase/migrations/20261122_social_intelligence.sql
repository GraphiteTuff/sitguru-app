-- Social Intelligence: additive, private provider-publication catalog and verified metric snapshots.
-- Read through role-checked Next.js handlers only; never return provider credentials.
create table if not exists public.growth_social_publications (
  id uuid primary key default gen_random_uuid(),
  platform text not null check (platform in ('facebook','instagram','tiktok','x','youtube')),
  provider_post_id text not null,
  studio_content_id uuid null,
  permalink text not null default '',
  title text not null default '',
  thumbnail_url text,
  published_at timestamptz,
  campaign_slug text not null default '',
  tracking_key text not null default '',
  source text not null default 'provider_api',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(platform,provider_post_id)
);
-- Staging may not contain the internship tables. Keep the migration reusable
-- and enforce a foreign key whenever Content Studio is installed.
do $social$
begin
  if to_regclass('public.internship_content') is not null then
    if not exists (
      select 1 from pg_constraint
      where conrelid = 'public.growth_social_publications'::regclass
        and conname = 'growth_social_publications_studio_content_id_fkey'
    ) then
      alter table public.growth_social_publications
        add constraint growth_social_publications_studio_content_id_fkey
        foreign key (studio_content_id)
        references public.internship_content(id) on delete set null;
    end if;
  end if;
end
$social$;
create index if not exists growth_social_publications_pub_idx
  on public.growth_social_publications (published_at desc);
create index if not exists growth_social_publications_campaign_idx
  on public.growth_social_publications (campaign_slug,published_at desc);
create table if not exists public.growth_social_post_metrics (
  id bigint generated by default as identity primary key,
  publication_id uuid not null references public.growth_social_publications(id) on delete cascade,
  captured_at timestamptz not null default now(),
  views bigint check (views is null or views >= 0),
  reach bigint check (reach is null or reach >= 0),
  likes bigint check (likes is null or likes >= 0),
  comments bigint check (comments is null or comments >= 0),
  shares bigint check (shares is null or shares >= 0),
  saves bigint check (saves is null or saves >= 0),
  follows bigint check (follows is null or follows >= 0),
  hook_rate numeric check (hook_rate is null or hook_rate between 0 and 100),
  average_watch_seconds numeric check (average_watch_seconds is null or average_watch_seconds >= 0),
  source text not null,
  metadata jsonb not null default '{}'::jsonb,
  unique(publication_id,captured_at)
);
create index if not exists growth_social_post_metrics_latest_idx
  on public.growth_social_post_metrics (publication_id,captured_at desc);
alter table public.growth_social_publications enable row level security;
alter table public.growth_social_post_metrics enable row level security;
revoke all on public.growth_social_publications from anon,authenticated;
revoke all on public.growth_social_post_metrics from anon,authenticated;
grant select,insert,update,delete on public.growth_social_publications to service_role;
grant select,insert,update,delete on public.growth_social_post_metrics to service_role;
grant usage,select on sequence public.growth_social_post_metrics_id_seq to service_role;
